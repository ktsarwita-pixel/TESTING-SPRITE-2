// Every pose has boots planted on row 27 (bottom row) so the angler NEVER floats on the pier.
// Legend:
//   k=#111622 outline, r/R=#c4383b/#8c1d24 red scarf/collar, a/A/q=#e8c170/#c79345/#f7e3a1 straw hat
//   s/S/p=#f6cca0/#d69b6c/#b0734a skin/shade, h=#472d1c hair
//   j/J/l=#2d8a68/#1d6149/#55b58a coastal jacket, u/U=#2f5a96/#1d3b68 denim jeans
//   b/B=#7d4e29/#472914 boots, w=#f8fafc eye white/highlight, g=#94a3b8 reel/belt buckle

function makePose(rows, hand, reelHand = null) {
  if (rows.length !== 28) throw new Error(`Expected 28 rows, got ${rows.length}`);
  const norm = rows.map((r) => {
    if (r.length > 24) throw new Error(`Row wider than 24: ${r.length}`);
    return r.padEnd(24, '.');
  });
  return { rows: norm, hand, reelHand: reelHand || [hand[0] - 2, hand[1] + 1] };
}

