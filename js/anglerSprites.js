// Anatomically consistent, zero-jump 24x28 16-bit angler sprite poses.
// ALL poses share the exact same planted boot anchor & vertical torso baseline so
// transitions between idle, ready-to-reel, bite, 4-frame cranking, and brace NEVER jump!

function makePose(rows, hand, reelHand = null) {
  if (rows.length !== 28) throw new Error(`Expected 28 rows, got ${rows.length}`);
  const norm = rows.map((r) => {
    if (r.length > 24) throw new Error(`Row wider than 24: ${r.length}`);
    return r.padEnd(24, '.');
  });
  return { rows: norm, hand, reelHand: reelHand || [hand[0] - 2, hand[1] + 1] };
}

